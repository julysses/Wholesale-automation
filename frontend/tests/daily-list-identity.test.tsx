import {fireEvent,render,screen,waitFor} from '@testing-library/react';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {beforeEach,expect,it,vi} from 'vitest';
const mocks=vi.hoisted(()=>({fetch:vi.fn()}));
vi.mock('@/lib/api',()=>({apiFetch:mocks.fetch}));
vi.mock('@/hooks/useProfile',()=>({useProfile:()=>({isAdmin:true})}));
vi.mock('@/components/lists/PropstreamHandoff',()=>({PropstreamHandoff:()=>null}));
vi.mock('@/components/lists/ForeclosureActions',()=>({ForeclosureActions:()=>null}));
vi.mock('@/components/lists/TraceOperations',()=>({TraceOperations:()=>null}));
vi.mock('@/components/lists/ScoringOperations',()=>({ScoringOperations:()=>null}));
vi.mock('@/components/lists/LotOperations',()=>({LotOperations:()=>null}));
import {ReviewControl} from '@/components/lists/ReviewControl';
const item={run_id:'synthetic',batch_index:0,ordinal:0,source_record_id:'account123',source_key:'tx-dallas-tax_delinquent',property_address:null,city:null,zip:null,unit:null,parcel_id:'parcel123',source_fingerprint:'a'.repeat(32),source_url:'https://www.dallascounty.org/synthetic',review_reason:'verify_property'};
beforeEach(()=>{vi.resetAllMocks();mocks.fetch.mockResolvedValue({json:async()=>({day:'2026-10-13',sources:[],runs:[],reviews:[item],review_count:1,digest:null})});});
it('shows historical tax amounts and holds without presenting them as current debt',()=>{
 render(<ReviewControl item={{...item,state:'TX',tax_snapshot:{snapshot_date:'2026-10-10',amount_cents:39,amount_kind:'balance',review_flags:'active_deferral_review',situs_missing:true}}} refresh={async()=>undefined}/>);
 expect(screen.getByRole('region',{name:'Historical tax evidence'})).toHaveTextContent('2026-10-10');
 expect(screen.getByText('Recorded balance: $0.39')).toBeInTheDocument();
 expect(screen.getByText('Tax deferral requires review')).toBeInTheDocument();
 expect(screen.getByText(/not a current payoff or confirmed active delinquency/)).toBeInTheDocument();
 expect(screen.getByRole('button',{name:'Save verified association'})).toBeDisabled();
});
it('keeps withheld or invalid historical amounts unavailable',()=>{
 render(<ReviewControl item={{...item,state:'TX',tax_snapshot:{snapshot_date:'not-a-date',amount_cents:'1234',amount_kind:'remaining_levy',review_flags:'duplicate_tax_row_review'}}} refresh={async()=>undefined}/>);
 expect(screen.getByText('Recorded remaining levy: Not available')).toBeInTheDocument();
 expect(screen.getByText(/Duplicate tax rows; aggregate amount withheld/)).toBeInTheDocument();
 expect(screen.getByRole('region',{name:'Historical tax evidence'})).toHaveTextContent('Date unavailable');
});
it('does not present or accept a zero-filled county address as verified situs',()=>{
 render(<ReviewControl item={{...item,property_address:'0000000',state:'TX'}} refresh={async()=>undefined}/>);
 expect(screen.getByRole('heading',{name:'Unresolved property'})).toBeInTheDocument();
 expect(screen.getByLabelText('Verified property street address')).toHaveValue('');
 fireEvent.change(screen.getByLabelText('Verified property street address'),{target:{value:'0000000'}});
 fireEvent.change(screen.getByLabelText('Verified property city (Texas)'),{target:{value:'Plano'}});
 fireEvent.change(screen.getByLabelText('Verified property ZIP'),{target:{value:'75024'}});
 fireEvent.change(screen.getByLabelText('Official county or title evidence URL'),{target:{value:'https://www.collincad.org/synthetic'}});
 fireEvent.change(screen.getByLabelText(/Evidence notes:/),{target:{value:'Independent evidence still needs a real situs.'}});
 fireEvent.click(screen.getByLabelText(/I verified the exact property/));
 expect(screen.getByRole('button',{name:'Save verified association'})).toBeDisabled();
 expect(mocks.fetch).not.toHaveBeenCalled();
});
it('requires independent situs evidence and submits a bound inactive review',async()=>{
 render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><ReviewControl item={item} refresh={async()=>undefined}/></QueryClientProvider>);
 const save=await screen.findByRole('button',{name:'Save verified association'});
 expect(save).toBeDisabled();
 fireEvent.change(screen.getByLabelText('Verified property street address'),{target:{value:'1 Verified Site'}});
 fireEvent.change(screen.getByLabelText('Verified property city (Texas)'),{target:{value:'Dallas'}});
 fireEvent.change(screen.getByLabelText('Verified property ZIP'),{target:{value:'75201'}});
 fireEvent.change(screen.getByLabelText('Official county or title evidence URL'),{target:{value:'https://www.dallascad.org/synthetic'}});
 fireEvent.click(screen.getByLabelText(/I verified the exact property/));
 expect(save).toBeDisabled();
 fireEvent.change(screen.getByLabelText(/Evidence notes:/),{target:{value:'Official parcel and situs independently matched.'}});
 expect(save).not.toBeDisabled();fireEvent.click(save);
 await waitFor(()=>expect(mocks.fetch.mock.calls.some(([url])=>url==='/api/operations/lists/resolve')).toBe(true));
 const call=mocks.fetch.mock.calls.find(([url])=>url==='/api/operations/lists/resolve');
 const body=JSON.parse(call![1].body);
 expect(body.active_signal).toBe(false);expect(body.review.source_fingerprint).toBe(item.source_fingerprint);
 expect(body.review.identity).toEqual({property_address:'1 Verified Site',city:'Dallas',state:'TX',zip:'75201',parcel_id:'parcel123',unit:null});
});
