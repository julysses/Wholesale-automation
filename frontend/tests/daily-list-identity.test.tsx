import {fireEvent,render,screen,waitFor} from '@testing-library/react';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {beforeEach,expect,it,vi} from 'vitest';
const mocks=vi.hoisted(()=>({fetch:vi.fn()}));
vi.mock('@/lib/api',()=>({apiFetch:mocks.fetch}));
vi.mock('@/hooks/useProfile',()=>({useProfile:()=>({isAdmin:true})}));
vi.mock('@/components/lists/TraceOperations',()=>({TraceOperations:()=>null}));
vi.mock('@/components/lists/ScoringOperations',()=>({ScoringOperations:()=>null}));
vi.mock('@/components/lists/LotOperations',()=>({LotOperations:()=>null}));
import {DailyLists} from '@/pages/DailyLists';
const item={run_id:'synthetic',batch_index:0,ordinal:0,source_record_id:'account123',source_key:'tx-dallas-tax_delinquent',property_address:null,city:null,zip:null,unit:null,parcel_id:'parcel123',source_fingerprint:'a'.repeat(32),source_url:'https://www.dallascounty.org/synthetic',review_reason:'verify_property'};
beforeEach(()=>{vi.resetAllMocks();mocks.fetch.mockResolvedValue({json:async()=>({day:'2026-10-13',sources:[],runs:[],reviews:[item],review_count:1,digest:null})});});
it('requires independent situs evidence and submits a bound inactive review',async()=>{
 render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><DailyLists/></QueryClientProvider>);
 const save=await screen.findByRole('button',{name:'Save verified association'});
 expect(save).toBeDisabled();
 fireEvent.change(screen.getByLabelText('Verified property street address'),{target:{value:'1 Verified Site'}});
 fireEvent.change(screen.getByLabelText('Verified property city (Texas)'),{target:{value:'Dallas'}});
 fireEvent.change(screen.getByLabelText('Verified property ZIP'),{target:{value:'75201'}});
 fireEvent.change(screen.getByLabelText('Official county or title evidence URL'),{target:{value:'https://www.dallascad.org/synthetic'}});
 fireEvent.click(screen.getByLabelText(/I verified the exact property/));
 expect(save).toBeDisabled();
 fireEvent.change(screen.getByLabelText(/Evidence notes:/),{target:{value:'Official parcel and situs independently matched.'}});
 expect(save).not.toBeDisabled();fireEvent.click(save);
 await waitFor(()=>expect(mocks.fetch.mock.calls.some(([url])=>url==='/api/operations/lists/resolve')).toBe(true));
 const call=mocks.fetch.mock.calls.find(([url])=>url==='/api/operations/lists/resolve');
 const body=JSON.parse(call![1].body);
 expect(body.active_signal).toBe(false);expect(body.review.source_fingerprint).toBe(item.source_fingerprint);
 expect(body.review.identity).toEqual({property_address:'1 Verified Site',city:'Dallas',state:'TX',zip:'75201',parcel_id:'parcel123',unit:null});
});
